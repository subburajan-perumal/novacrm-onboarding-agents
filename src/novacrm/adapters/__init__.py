"""External integrations. Each adapter has a Protocol so tests can swap in fakes."""
from __future__ import annotations

from typing import Optional, Protocol

from ..models import CallOutcome, DealExtraction, InboundEmail, TranscriptJudgement


class MailClient(Protocol):
    def list_new(self, query: str) -> list[InboundEmail]: ...
    def thread_text(self, thread_id: str) -> str: ...
    def add_labels(self, message_id: str, labels: list[str]) -> None: ...
    def reply(self, email: InboundEmail, body: str, reply_to: Optional[str] = None) -> None: ...
    def send(self, to: str, subject: str, body: str) -> None: ...


class LLMClient(Protocol):
    def extract_deal(self, email_text: str) -> DealExtraction: ...
    def judge_transcript(self, transcript: str, customer_name: str) -> TranscriptJudgement: ...
    def draft_welcome(self, facts: dict) -> str: ...


class VoiceClient(Protocol):
    def place_call(self, *, to_number: str, ae_name: str, customer_name: str, run_id: str, attempt: int) -> CallOutcome: ...


class ProjectClient(Protocol):
    def find_existing_projects(self, customer_name: str, opportunity_id: str) -> list[dict]: ...
    def create_project(self, payload: dict) -> dict: ...
    def list_tasks(self, project_id: int) -> list[dict]: ...
    def find_user_id(self, email: str) -> Optional[int]: ...


class ChatClient(Protocol):
    def find_channel(self, name: str) -> Optional[str]: ...
    def create_channel(self, name: str) -> str: ...
    def set_topic(self, channel_id: str, topic: str) -> None: ...
    def set_purpose(self, channel_id: str, purpose: str) -> None: ...
    def post_message(self, channel: str, text: str) -> None: ...
    def lookup_user(self, email: str) -> Optional[str]: ...
    def invite(self, channel_id: str, user_ids: list[str]) -> None: ...
